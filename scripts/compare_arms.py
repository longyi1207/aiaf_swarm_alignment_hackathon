#!/usr/bin/env python3
"""Arm comparisons for main_v4 (all 7 arms), world-paired bootstrap.

Each arm ran the same 8 worlds (seeds 201–202 × harm medium/high × discuss/isolated), so differences are paired by
world: per world, the arm's share of agents filing on Channel E minus the comparison arm's share; the CI resamples
worlds (10,000 draws). Also reports filing channels, agents with no filing, and agents with a forced phase end.

    python scripts/compare_arms.py runs/main_v4 > results/main_v4/arm_comparisons.md
"""

from __future__ import annotations

import csv
import json
import random
import statistics as st
import sys
from collections import Counter, defaultdict
from pathlib import Path

ARMS = ["none", "emp", "random", "tom", "random_tom", "tom_all30", "random_all30"]
LABEL = {"none": "no lesion", "emp": "empathy (emp_coarse_all_a70)", "random": "random, matched to emp",
         "tom": "ToM v2 layer 6 (tom2_L6)", "random_tom": "random, matched to tom",
         "tom_all30": "ToM v2 all layers α0.3 (tom2_all_a30)", "random_all30": "random, matched to tom_all30"}
PAIRS = [("emp", "random"), ("tom", "random_tom"), ("tom_all30", "random_all30")]


def paired(rate: dict, worlds: list[str], a: str, b: str, n: int = 10000, seed: int = 0) -> dict:
    ws = [w for w in worlds if (a, w) in rate and (b, w) in rate]
    d = [rate[(a, w)] - rate[(b, w)] for w in ws]
    rng = random.Random(seed)
    boots = sorted(st.fmean(rng.choices(d, k=len(d))) for _ in range(n))
    p = 2 * min(sum(x <= 0 for x in boots), sum(x >= 0 for x in boots)) / n
    return {"diff": st.fmean(d), "ci": [boots[int(0.025 * n)], boots[int(0.975 * n) - 1]], "p": min(p, 1.0),
            "worlds": len(ws), "lower_in": sum(x < 0 for x in d), "higher_in": sum(x > 0 for x in d)}


def main() -> int:
    run = Path(sys.argv[1])
    rows = list(csv.DictReader(open(run / "results" / "agents.csv")))
    per_world = defaultdict(list)
    for r in rows:
        per_world[(r["lesion_tag"], r["world_id"])].append(int(r["filed_e"]))
    rate = {k: st.fmean(v) for k, v in per_world.items()}
    worlds = sorted({w for _, w in per_world})
    chan, forced = defaultdict(Counter), Counter()
    for g in sorted((run / "games").iterdir()):
        arm = g.name.split("__")[1]
        s = json.loads((g / "state.json").read_text())
        for a in s["agents"].values():
            chan[arm][(a.get("filing") or {}).get("channel", "none")] += 1
            forced[arm] += bool(a.get("forced"))
    out = {"arms": {}, "vs_none": {}, "vs_matched_random": {}}
    print("# main_v4: arm comparisons (world-paired bootstrap)\n")
    print(f"Worlds: {len(worlds)} (each arm ran all of them; 5 agents per game). Generated by `scripts/compare_arms.py`.\n")
    print("| arm | lesion | Channel E | Channel I | no filing | forced phase end |")
    print("|---|---|---|---|---|---|")
    for arm in ARMS:
        c = chan[arm]; n = sum(c.values())
        out["arms"][arm] = {"E": c.get("E", 0), "I": c.get("I", 0), "none": c.get("none", 0), "forced": forced[arm], "n": n}
        print(f"| {arm} | {LABEL[arm]} | {c.get('E', 0)}/{n} ({c.get('E', 0) / n:.1%}) | {c.get('I', 0)} | "
              f"{c.get('none', 0)} | {forced[arm]} |")
    print("\n## Filing on Channel E, arm − no lesion\n")
    print("| arm | difference | 95% CI | p (two-sided, bootstrap) | worlds lower / higher |")
    print("|---|---|---|---|---|")
    for arm in ARMS[1:]:
        r = paired(rate, worlds, arm, "none")
        out["vs_none"][arm] = r
        print(f"| {arm} | {r['diff']:+.3f} | [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}] | {r['p']:.3f} | "
              f"{r['lower_in']} / {r['higher_in']} |")
    print("\n## Filing on Channel E, lesion − its matched random control\n")
    print("| comparison | difference | 95% CI | p | worlds lower / higher |")
    print("|---|---|---|---|---|")
    for a, b in PAIRS:
        r = paired(rate, worlds, a, b)
        out["vs_matched_random"][f"{a}-{b}"] = r
        print(f"| {a} − {b} | {r['diff']:+.3f} | [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}] | {r['p']:.3f} | "
              f"{r['lower_in']} / {r['higher_in']} |")
    print("\nNo correction for multiple comparisons is applied in this table (9 comparisons); read p-values accordingly.")
    (run / "results" / "arm_comparisons.json").write_text(json.dumps(out, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
